/**
 * Generate exactly 100 educational slides for Module 1.
 * 2 slides per vocabulary item:
 * - Slide A (Odd number: 1, 3, 5... 99): Spanish Only
 * - Slide B (Even number: 2, 4, 6... 100): Spanish + English
 */
export function generateModule1Slides(): SlideData[] {
  const slides: SlideData[] = [];

  VOCABULARY_LIST.forEach((item, index) => {
    const itemNumber = index + 1;
    const slideANumber = (itemNumber - 1) * 2 + 1; // 1, 3, 5, ...
    const slideBNumber = slideANumber + 1;         // 2, 4, 6, ...

    // Slide A: Spanish Only
    slides.push({
      id: `m1-item-${item.id}-a`,
      module: 1,
      slideNumberInScope: slideANumber,
      totalInScope: 100,
      kind: 'vocab_spanish',
      vocabItem: item,
    });

    // Slide B: Spanish + English
    slides.push({
      id: `m1-item-${item.id}-b`,
      module: 1,
      slideNumberInScope: slideBNumber,
      totalInScope: 100,
      kind: 'vocab_bilingual',
      vocabItem: item,
    });
  });

  return slides;
}
