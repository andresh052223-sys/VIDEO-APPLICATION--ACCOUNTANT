/**
 * Generate exactly 48 educational slides for Module 2.
 * 4 sections, 6 pairs each = 24 pairs * 2 = 48 slides.
 */
export function generateModule2Slides(sectionFilter?: 'personal' | 'academic' | 'experience' | 'skills'): SlideData[] {
  const filteredPairs = sectionFilter
    ? GRAMMAR_PAIRS.filter((p) => p.sectionId === sectionFilter)
    : GRAMMAR_PAIRS;

  const slides: SlideData[] = [];
  const sectionTitleMap: Record<string, string> = {
    personal: 'Personal Information',
    academic: 'Academic Information',
    experience: 'Accounting Experience',
    skills: 'My Accounting Skills',
  };

  filteredPairs.forEach((pair, index) => {
    const pairNumber = index + 1;
    const slideANumber = (pairNumber - 1) * 2 + 1; // 1, 3, 5, 7, 9, 11
    const slideBNumber = slideANumber + 1;         // 2, 4, 6, 8, 10, 12
    const totalCount = sectionFilter ? 12 : 48;

    // Slide A: Spanish Only
    slides.push({
      id: `m2-${pair.sectionId}-p${pair.pairIndex}-a`,
      module: 2,
      sectionId: pair.sectionId,
      sectionTitle: sectionTitleMap[pair.sectionId],
      slideNumberInScope: slideANumber,
      totalInScope: totalCount,
      kind: 'grammar_spanish',
      grammarItem: pair,
    });

    // Slide B: Spanish + English
    slides.push({
      id: `m2-${pair.sectionId}-p${pair.pairIndex}-b`,
      module: 2,
      sectionId: pair.sectionId,
      sectionTitle: sectionTitleMap[pair.sectionId],
      slideNumberInScope: slideBNumber,
      totalInScope: totalCount,
      kind: 'grammar_bilingual',
      grammarItem: pair,
    });
  });

  return slides;
}
